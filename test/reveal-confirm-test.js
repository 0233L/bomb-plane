// ============================================
// test/reveal-confirm-test.js —— 探测「二次确认」交互测试（jsdom 实测）
// 验证：默认关闭时点一次就探测；开启后第一次只选中、第二次点同一格才探测；
//       改点别的格子 = 改选；道具选区优先，不受影响；守卫格不设待确认目标；
//       勾选状态写入 localStorage，观战/对局结束时隐藏勾选框。
// 用法：node test/reveal-confirm-test.js
// 说明：client.js 是严格模式 + 顶层 init，state 在 eval 作用域内取不到，
//       所以被测源码和测试代码合并成一段脚本一次 eval（同一作用域）。
// ============================================
'use strict';
const { JSDOM } = require('jsdom');
const fs = require('fs');

const html = fs.readFileSync('public/index.html', 'utf8');
const wsSrc = fs.readFileSync('public/ws.js', 'utf8');
const sharedSrc = fs.readFileSync('public/shared.js', 'utf8');
const clientSrc = fs.readFileSync('public/client.js', 'utf8');

const dom = new JSDOM(html, { url: 'http://localhost:3000/', runScripts: 'outside-only', pretendToBeVisual: true });
const win = dom.window;
win.WebSocket = require('ws').WebSocket; // init 里 WSClient 会真实连接本地服务器
win.matchMedia = function () { // jsdom 不提供 matchMedia，给个最小实现
  return { matches: false, addEventListener: function () {}, removeEventListener: function () {} };
};

// 测试代码与被测源码同一 eval 作用域：能直接访问 state / onEnemyCellClick
const testSrc = [
  'window.__revealTest = function () {',
  '  var passed = 0, failed = 0, lines = [], emits = [];',
  '  function check(name, cond) {',
  '    if (cond) { passed++; lines.push("  ✓ " + name); }',
  '    else { failed++; lines.push("  ✗ " + name); }',
  '  }',
  '  function lastEmit() { return emits[emits.length - 1]; }',
  '  function resetBattle() {',
  '    state.boardSize = "S";',
  '    state.seat = 0;',
  '    state.spectator = false;',
  '    state.over = false;',
  '    state.revealedPlanes = null;',
  '    state.myPlanes = [];',
  '    state.myShotsReceived = [];',
  '    state.enemyShotsReceived = [];',
  '    state.sonarResults = [];',
  '    state.frozenCells = [];',
  '    state.coins = [0, 0];',
  '    state.steps = [0, 0];',
  '    state.marks = {};',
  '    state.mode = "classic";',
  '    state.itemPick = null;',
  '    state.pickCells = [];',
  '    state.pickAnchor = null;',
  '    state.pickReady = false;',
  '    state.pickFirstKey = null;',
  '    state.pickHover = [];',
  '    state.revealPending = null;',
  '    state.revealConfirm = false;',
  '    localStorage.removeItem("bp_reveal_confirm");',
  '    emits = [];',
  '    updateRevealConfirmUI();',
  '    renderBattleBoards();',
  '  }',
  '  function hasTarget(r, c) {',
  '    var td = document.querySelector("#enemy-board td[data-row=\\"" + r + "\\"][data-col=\\"" + c + "\\"]");',
  '    return !!(td && td.classList.contains("cell-probe-target"));',
  '  }',
  '  function toggle(on) {',
  '    var box = document.getElementById("reveal-confirm");',
  '    box.checked = on;',
  '    box.dispatchEvent(new Event("change", { bubbles: true }));',
  '  }',
  '  state.socket.emit = function (ev, data) { emits.push({ ev: ev, data: data }); };',
  '  resetBattle();',
  '',
  '  // ===== 1. 默认关闭：点一次立即探测 =====',
  '  lines.push("1. 默认关闭");',
  '  check("默认未勾选", document.getElementById("reveal-confirm").checked === false);',
  '  check("state 默认关闭", state.revealConfirm === false);',
  '  check("勾选框可见", !document.getElementById("reveal-confirm-wrap").classList.contains("hidden"));',
  '  onEnemyCellClick(2, 2);',
  '  check("关闭时点一次立即 emit reveal", emits.length === 1 && lastEmit().ev === "reveal");',
  '  check("坐标正确", lastEmit().data.row === 2 && lastEmit().data.col === 2);',
  '  check("没有待确认目标", state.revealPending === null);',
  '',
  '  // ===== 2. 开启：第一次选中，第二次同一格才探测 =====',
  '  lines.push("2. 开启二次确认");',
  '  toggle(true);',
  '  check("state 已开启", state.revealConfirm === true);',
  '  check("选择写入 localStorage", localStorage.getItem("bp_reveal_confirm") === "1");',
  '  check("副标题提示二次确认", document.getElementById("board-title-enemy-note").textContent.indexOf("二次确认") !== -1);',
  '  emits = [];',
  '  onEnemyCellClick(3, 4);',
  '  check("第一次点不发送", emits.length === 0);',
  '  check("记录待确认目标", state.revealPending && state.revealPending.row === 3 && state.revealPending.col === 4);',
  '  check("目标格有虚线高亮", hasTarget(3, 4));',
  '  onEnemyCellClick(3, 5);',
  '  check("点另一格不发送", emits.length === 0);',
  '  check("改为新目标", state.revealPending && state.revealPending.row === 3 && state.revealPending.col === 5);',
  '  check("旧目标高亮消失", !hasTarget(3, 4));',
  '  check("新目标高亮出现", hasTarget(3, 5));',
  '  onEnemyCellClick(3, 5);',
  '  check("第二次点同一格只发送一次", emits.length === 1 && lastEmit().ev === "reveal");',
  '  check("发送正确坐标", lastEmit().data.row === 3 && lastEmit().data.col === 5);',
  '  check("发送后清空目标", state.revealPending === null);',
  '  check("发送后虚线高亮消失", !hasTarget(3, 5));',
  '',
  '  // ===== 3. 道具选区优先：点格子只走 pickItemCell =====',
  '  lines.push("3. 道具选区不受影响");',
  '  emits = [];',
  '  state.revealPending = null;',
  '  state.itemPick = { itemId: "sonar" };',
  '  state.pickCells = [];',
  '  state.pickAnchor = null;',
  '  state.pickReady = false;',
  '  onEnemyCellClick(4, 4);',
  '  check("道具模式下点击进入选区", state.pickReady === true && state.pickAnchor !== null);',
  '  check("不发送普通 reveal", emits.length === 0);',
  '  check("不设置待确认目标", state.revealPending === null);',
  '  clearItemPick();',
  '  renderBattleBoards();',
  '',
  '  // ===== 4. 各种守卫：不设待确认目标 =====',
  '  lines.push("4. 守卫格不设目标");',
  '  state.revealConfirm = true;',
  '  state.enemyShotsReceived = [{ row: 1, col: 1, result: "empty" }];',
  '  emits = [];',
  '  onEnemyCellClick(1, 1);',
  '  check("已揭示格被拒", emits.length === 0 && state.revealPending === null);',
  '  state.enemyShotsReceived = [];',
  '  state.frozenCells = [{ row: 2, col: 2, owner: 0, expiry: 2 }];',
  '  state.steps = [1, 1];',
  '  onEnemyCellClick(2, 2);',
  '  check("冻结格被拒", emits.length === 0 && state.revealPending === null);',
  '  state.frozenCells = [];',
  '  state.steps = [2, 1];',
  '  onEnemyCellClick(2, 3);',
  '  check("步数领先被拒", emits.length === 0 && state.revealPending === null);',
  '  state.steps = [0, 0];',
  '  state.spectator = true;',
  '  onEnemyCellClick(2, 4);',
  '  check("观战被拒", emits.length === 0 && state.revealPending === null);',
  '  state.spectator = false;',
  '  state.over = true;',
  '  onEnemyCellClick(2, 5);',
  '  check("对局结束被拒", emits.length === 0 && state.revealPending === null);',
  '  state.over = false;',
  '  updateRevealConfirmUI();',
  '',
  '  // ===== 5. 关闭开关：清掉未确认目标，恢复默认文案 =====',
  '  lines.push("5. 关闭二次确认");',
  '  state.revealPending = { row: 5, col: 5 };',
  '  renderBattleBoards();',
  '  check("关闭前目标高亮存在", hasTarget(5, 5));',
  '  toggle(false);',
  '  check("state 已关闭", state.revealConfirm === false);',
  '  check("关闭写入 localStorage", localStorage.getItem("bp_reveal_confirm") === "0");',
  '  check("关闭清空待确认目标", state.revealPending === null);',
  '  check("关闭后高亮消失", !hasTarget(5, 5));',
  '  check("副标题恢复默认文案", document.getElementById("board-title-enemy-note").textContent.indexOf("点击未知格子") !== -1);',
  '  emits = [];',
  '  onEnemyCellClick(6, 6);',
  '  check("关闭后点一次立即探测", emits.length === 1 && lastEmit().ev === "reveal");',
  '',
  '  // ===== 6. 读取记忆 + 观战/结束隐藏 =====',
  '  lines.push("6. 记忆与可见性");',
  '  localStorage.setItem("bp_reveal_confirm", "1");',
  '  loadRevealConfirm();',
  '  check("读取记忆后开启", state.revealConfirm === true && document.getElementById("reveal-confirm").checked === true);',
  '  state.spectator = true;',
  '  updateRevealConfirmUI();',
  '  check("观战隐藏勾选框", document.getElementById("reveal-confirm-wrap").classList.contains("hidden"));',
  '  state.spectator = false;',
  '  state.over = true;',
  '  updateRevealConfirmUI();',
  '  check("对局结束隐藏勾选框", document.getElementById("reveal-confirm-wrap").classList.contains("hidden"));',
  '  state.over = false;',
  '  updateRevealConfirmUI();',
  '  check("回到对局重新显示勾选框", !document.getElementById("reveal-confirm-wrap").classList.contains("hidden"));',
  '  localStorage.setItem("bp_reveal_confirm", "0");',
  '',
  '  return { passed: passed, failed: failed, lines: lines };',
  '};'
].join('\n');

win.eval(wsSrc + '\n' + sharedSrc + '\n' + clientSrc + '\n' + testSrc);
const res = win.__revealTest();
res.lines.forEach(function (l) { console.log(l); });
console.log('\n结果: ' + res.passed + ' 通过, ' + res.failed + ' 失败');
process.exitCode = res.failed ? 1 : 0;
setTimeout(function () { process.exit(process.exitCode); }, 500); // 等 ws 连接回收
